function OpenAirplaneDoor(%this, %close)
{
	if(!%close) 
	{
		%this.status = "open";
		%this.closetime = getsimtime()+3;
		%this.delay = getsimtime()+3;
		Moveable::moveToWaypoint(%this,0);				
	}
	else 
	{ 
	Moveable::moveToWaypoint(%this,1);				
	}
}
