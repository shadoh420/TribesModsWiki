function Door::onMove(%this, %forceClose)
{
	
   if(!%this.iscell){
	if($ForceFields[GameBase::getDataName(%this)] != "" && %this.faded == "" && %this.status == "open") {
		GameBase::startFadeOut(%this);
		%time = getSimTime() - %this.fadeTime;
		if(%time > 2.5)
			%time = 2.5;
		%this.faded = 1;
		if(%forceClose != "")
			schedule("Door::onMove(" @ %this @ "," @ %forceClose @ ");",%time,%this);
		else
			schedule("Door::onMove(" @ %this @ ");",%time,%this);
		schedule("GameBase::playSound(" @ %this @ ",ForceFieldOpen,0);",(%time/2),%this);
		return;		
	} 
	if((GameBase::isActive(%this) && GameBase::isPowered(%this)) || %forceClose != "") {
		if(%this.status == "open") {
			if((GameBase::getDataName(%this)).side == "left")
				Moveable::moveToWaypoint(%this,(Moveable::getWaypointCount(%this)-1));				
			else
				Moveable::moveToWaypoint(%this,0);				
	 	}
		else { 
			Moveable::moveToWaypoint(%this,%this.center);				
		}
	}
	if($ForceFields[GameBase::getDataName(%this)] != "" && %this.status == "close" && !%this.faded == "" && GameBase::isPowered(%this)) {
		GameBase::startFadeIn(%this);
	 	%this.faded="";
		%this.fadeTime = getSimTime();
	}
   }
}
function LiftDoorCheck(%this, %object)
{
	if(Player::isAIControlled(%object))
	{
		//echo("AI Door Check.");	
		return;
	}
	if(Player::isDead(%object) || getObjectType(%object) != "Player") 
	{
		//echo("Door check dead...");
		return;
	}
	%y = 0;
	%master = getgroup(getgroup(%this));
	for(%x = 0; %x < Group::objectCount(%master); %x++)
	{
		%group = group::getobject(%master, %x);
		if(String::findSubStr(objecT::getname(%group), "Lift")!=-1)
		{
			%lift[%y] = Group::getObject(%group, 1);
			//echo("Lift #"@%y@" = "@%lift[%y]@" at "@Moveable::getPosition(%lift[%y])@" moving: "@%lift[%y].moving);
			%y++;
		}
	}
	%doorpos = 1;
	%str = "Bottom";
	//echo(objecT::getname(getgroup(%this)));
	if(String::findSubStr(objecT::getname(getgroup(%this)), "Top")!=-1)
	{	
		%str = "Top";
		%doorpos = 0;
	}
	if(Moveable::getPosition(%lift[0])==%doorpos&&%lift[0].moving == false)
	{
		OpenDoors(%str, %master, 0);
	}
	else
	{
	if(FullElevator::Call(%lift[0], %object))
		client::sendmessage(player::getclient(%object), 1, "Calling Lift...");
	
	}
}
function Door::onCollision(%this, %object)
{
	
	%cl = player::getclient(%object);
	if(String::FindSubStr(object::getname(getgroup(%this)), "DECOR") != -1)
		if(vector::Getdistance(gamebase::getposition(%this), gamebase::getposition(%object))<2.5)
			if(!%cl.NoDoorMessage)
			{
			%cl.NoDoorMessage = 1;
			schedule(%cl@".NoDoorMessage = 0;", 5);
			client::sendmessage(%cl, 1, "This door seems to be locked.");
			}

	if(!Player::isDead(%object) && getObjectType(%object) == "Player") 
	{
		if (GameBase::isActive(%this) && GameBase::isPowered(%this) && %this.faded == "")  
		{
			if(GameBase::getTeam(%this) == GameBase::getTeam(%object) || GameBase::getTeam(%this) == -1 || %this.noTeam != "" ) 
			{
				if((%this.triggerOpen == "" || %this.triggerTrigger) ) 
				{
					if(%this.isliftdoor)
						LiftDoorCheck(%this, %object);
					if(!%this.isCell)
						{
						Door::trigger(%this);
						}
				}
			}
		}
	}
}

