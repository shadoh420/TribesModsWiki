{
	%this.moving = false;
	%this.status = "up";
	%this.delayTime = getSimTime() + 1.5;
	%this.triggerHit = "";
	OpenDoors("Top", getgroup(getgroup(%this)), 0);
}  

function FullElevator::Call(%this, %object)
{
	if(%this.called)
		return false;
	if(!Player::isDead(%object) && getObjectType(%object) == "Player")
		if (GameBase::getTeam(%this) == GameBase::getTeam(%object) || %this.noTeam != "" || GameBase::getTeam(%this) == -1) {
			if (GameBase::isActive(%this) && %this.loop == "" && GameBase::isPowered(%this)  && getSimTime() >= %this.delayTime) {
				%this.called = 1;
				%wp = Moveable::getPosition(%this);
				%doors = GetDoorsForPos(%this, %wp);
				if(Moveable::getPosition(Group::GetObject(%doors, 1)) == 1 && Moveable::getPosition(Group::GetObject(%doors, 2)) == 1)
				{
					
					%this.called = 0;
					FullElevator::onMove(%this);
					return true;
				} else
				{
				schedule("FullElevator::RealcheckDelay(" @ %this @ ");",1,%this);

				}
			}
			else if(GameBase::getDataName(%object) == AntipersonelMine) 
				AntipersonelMine::onCollision(%object,%this);
		}
	return false;
}

function FullElevator::RealCheckDelay(%this)
{
	if(!%this.called)
		return;
	
	
	%wp = Moveable::getPosition(%this);
	%doors = GetDoorsForPos(%this, %wp);
		if(Moveable::getPosition(Group::GetObject(%doors, 1)) == 1 && Moveable::getPosition(Group::GetObject(%doors, 2)) == 1)
			{
			
			%this.called = 0;
			FullElevator::onMove(%this);
			return;
			}
		else
			schedule("FullElevator::RealcheckDelay(" @ %this @ ");",1,%this);

}


function OpenDoors(%pos, %master, %close)
{

	//echo("CALLED: OpenDoors("@%pos@", "@%master@", "@%close@")");
	for(%x = 0; %x < Group::objectCount(%master); %x++)
	{
		%group = group::getobject(%master, %x);
		
		if(String::findSubStr(objecT::getname(%group), "Door "@%pos)!=-1)
		{
			
			%door[0] = Group::getObject(%group, 1);
			%door[1] = Group::getObject(%group, 2);
			for(%y = 0; %y < 2; %y++)
			{
				%this = %door[%y];
				%this.status = "open";
				%this.delay = 0;
				if(getsimtime()>%this.delay||%this.closing)
				{	
					
					%this.closing = false;
					if(!%close) 
					{
						%this.opening = true;
						%this.status = "open";
						%this.closetime = getsimtime()+3;
						%this.delay = getsimtime()+3;
						if((GameBase::getDataName(%this)).side == "left")
							Moveable::moveToWaypoint(%this,(Moveable::getWaypointCount(%this)-1));				
						else
							Moveable::moveToWaypoint(%this,0);
						
						Door::LiftcloseCheck(%this, %pos, %master);			
	 				}
					else 
					{ 
						
						%this.delay = getsimtime()+3;
					
					
						Moveable::moveToWaypoint(%this,1);				
					}
				}
			}
		}
	}
	
}
function Door::LiftcloseCheck(%this, %pos, %master)
{
   	//echo("CALLED:  Door::LiftcloseCheck("@%this@", "@%pos@", "@%master@")");
	if (getSimTime() >= %this.closeTime)
	{
		%this.opening = false;
		%this.closing = true;
		
		OpenDoors(%pos, %master, 1);
	}
	else
	{
		
		schedule("Door::LiftcloseCheck(" @ %this @ ", "@%pos@" ,"@%master@");",1,%this);
	}
}

