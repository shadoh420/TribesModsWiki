function FullElevator::onMove(%this)
{
	if(GameBase::isPowered(%this) && GameBase::isActive(%this)) {	
		%this.moving = true;
		FullElevator::MoveGroup(%this);
		
		if(%this.status == "up")  
			Moveable::moveToWaypoint(%this,Moveable::getPosition(%this)+1);				
		else if(%this.status == "down")
			Moveable::moveToWaypoint(%this,Moveable::getPosition(%this)-1);				
		%this.triggered = "";
	}
}

function FullElevator::MoveGroup(%this)
{
	%master = getgroup(getgroup(%this));
	for(%x = 0; %x < Group::objectCount(%master); %x++)
	{
		%group = group::getobject(%master, %x);
		if(String::findSubStr(objecT::getname(%group), "Lift")!=-1)
		{
			%lift = Group::getObject(%group, 1);
			if(%lift.moving != true)
			{
				FullElevator::onMove(%lift);
			}
		}
	}
}

