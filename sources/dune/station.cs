			%item = getItemData(%i);
			// Part of ifcheck below. 
			if($RemoteInvList[%item] != "" && $RemoteInvList[%item] && !%station.dontSell[%item] && $ItemMax[%armor,%item] > 0 && !$TeamRestrictedItem[$ServerNameToKeyName[client::getteam(%client)],%armor, %item]) 
