		for(%i = 0; %i < %max; %i++) {						
			%item = getItemData(%i);
			// Part of ifcheck below. 
			if($InvList[%item] != "" && $InvList[%item] && !%station.dontSell[%item] && $ItemMax[%armor,%item] > 0 && !$TeamRestrictedItem[$ServerNameToKeyName[client::getteam(%client)],%armor, %item]) 
