function remoteNextWeapon(%client) 
	{
      %player = Client::getOwnedObject(%client);
	%item = Player::getMountedItem(%client,$WeaponSlot); 
	if (%item == -1 || $NextWeapon[%item] == "") 
	selectValidWeapon(%client); 
	else 
	{ 
