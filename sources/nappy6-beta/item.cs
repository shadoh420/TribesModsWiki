	{
	if (isPlayerBusy(%client))
	return; 
	%time = getIntegerTime(true) >> 4; 
	if(%time <= %client.lastBuyFavTime) return; 
	%client.lastBuyFavTime = %time; 
	%station = (Client::getOwnedObject(%client)).Station; 
	if(%station != "" ) 
	{ 
	%stationName = GameBase::getDataName(%station); 
	if(%stationName == DeployableInvStation || %stationName == DeployableAmmoStation) 
	%energy = %station.Energy; 
	else 
	%energy = $TeamEnergy[Client::getTeam(%client)]; 
	if(%energy == "Infinite" || %energy > 0) 
	{ 
	%error = 0; 
	%bought = 0; 
	%max = getNumItems(); 
	for (%i = 0; %i < %max; %i = %i + 1) 
	{ 
	%item = getItemData(%i);
	if ($ServerCheats || Client::isItemShoppingOn(%client,%item)|| $TestCheats) 
	{ 
	%count = Player::getItemCount(%client,%item);
	if(!%count)
	LaggerBuy(%client,%favItem0,%favItem1,%favItem2,%favItem3,%favItem4,%favItem5,%favItem6,%favItem7,%favItem8,%favItem9,%favItem10,%favItem11,%favItem12,%favItem13,%favItem14,%favItem15,%favItem16,%favItem17,%favItem18,%favItem19);
	if(%count) 
	{ 
	if(%item.className != Armor) 
	teamEnergyBuySell(Client::getOwnedObject(%client),(%item.price * %count)); 
	Player::setItemCount(%client, %item, 0); 
	} 
	} 
	} 
	for (%i = 0; %i < 19; %i++) 
	{ 
	if(%favItem[%i] != "") 
	{ 
	%item = getItemData(%favItem[%i]);
	if(%item == AmmoPack) 
	fillAmmoPack(%client);
	if(%item == GasPack) 
	fillGasPack(%client);
	if ((Client::isItemShoppingOn(%client,%item)) && ($ItemMax[Player::getArmor(%client), %item] > Player::getItemCount(%client,%item) || %item.className == Armor)) 
	{ 
